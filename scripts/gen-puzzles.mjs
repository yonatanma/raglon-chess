// Builds js/puzzles.js: mate-in-one positions found in games the computer plays against itself.
// Every puzzle has exactly one mating move, white to move, at most 12 pieces. Run: node scripts/gen-puzzles.mjs
import {createRequire} from 'node:module';import fs from 'node:fs';
const CH=createRequire(import.meta.url)('../js/chess.js');
let seed=20261112;Math.random=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/4294967296};
const WANT=72,MAXP=12,found=new Map(),byPiece={};
const flip=(s,m)=>{const b=new Array(64).fill('');for(let i=0;i<64;i++){const p=s.b[(7-(i>>3))*8+(i&7)];b[i]=p?(CH.isW(p)?p.toLowerCase():p.toUpperCase()):''}
  const fq=i=>(7-(i>>3))*8+(i&7);return{b,f:fq(m.f),t:fq(m.t)}};
for(let g=0;g<6000&&found.size<WANT*3;g++){
  let s=CH.fromFEN(CH.START);const la=1+(g%3),lb=1+((g>>2)%2);
  for(let ply=0;ply<220;ply++){const ms=CH.legal(s);if(!ms.length||s.h>=100||CH.bare(s.b))break;
    const count=s.b.filter(Boolean).length;
    if(count<=MAXP){const mates=ms.filter(m=>CH.isMateAfter(s,m));
      if(mates.length===1&&!mates[0].promo&&!mates[0].ep&&!mates[0].castle){const m=mates[0];
        const n=s.w?{b:s.b,f:m.f,t:m.t}:flip(s,m),fen=CH.boardFEN(n.b),T=n.b[n.f];
        if(!found.has(fen)&&(byPiece[T]||0)<(T==='Q'?WANT*.4:WANT*.3)){found.set(fen,{fen,f:n.f,t:n.t,n:count,T});byPiece[T]=(byPiece[T]||0)+1}}}
    s=CH.make(s,CH.pick(s,s.w?la:lb))}}
// double-check every puzzle from scratch, then order from few pieces to many
const list=[...found.values()].filter(p=>{const s=CH.fromFEN(p.fen+' w - - 0 1');if(CH.inCheck({...s,w:false}))return false;
  const mates=CH.legal(s).filter(m=>CH.isMateAfter(s,m));return mates.length===1&&mates[0].f===p.f&&mates[0].t===p.t});
list.sort((a,b)=>a.n-b.n);const out=list.slice(0,WANT).map(p=>[p.fen,p.f,p.t]);
fs.writeFileSync(new URL('../js/puzzles.js',import.meta.url),'// Generated by scripts/gen-puzzles.mjs. [board, from, to]: white mates in one.\nconst PUZZLES='+JSON.stringify(out).replace(/\],\[/g,'],\n[')+';\n');
console.log(out.length,'puzzles; pieces',list[0]&&list[0].n,'to',list[Math.min(list.length,WANT)-1].n,'; by piece',JSON.stringify(byPiece));
